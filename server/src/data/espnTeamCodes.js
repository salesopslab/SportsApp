const CODES_BY_SPORT = {
  nfl: ESPN_NFL_CODES,
  nba: ESPN_NBA_CODES,
  mlb: ESPN_MLB_CODES,
};

export function toEspnCode(sportSlug, fullName) {
  const table = CODES_BY_SPORT[sportSlug];
  if (!table) return null;
  return table[fullName] || null;
}
